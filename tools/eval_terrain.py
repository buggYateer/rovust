"""Evidence for the terrain classifier: what it was trained on and how good it is.

    python tools/eval_terrain.py

The training images are not files on disk: they are generated by the camera's
texture model (sim/sensors/camera.py, ``synth_patch``), 500 per class x 7
classes = 3 500 images, with a fixed seed, so anyone can regenerate the exact
same set. 80 % train the forest, 20 % (700 images) are held out for the score.

This script:
  1. loads the model the program ships with (sim/ai/terrain_rf.pkl) and prints
     its held-out accuracy (measured when it was trained),
  2. tests it again on 1 400 NEW images it has never seen (another seed),
     prints the per-class accuracy and the confusion matrix,
  3. reads the live accuracy each mission measured on the real camera frames
     (reports/*/metrics.json, read only),
  4. saves docs/figures/terrain_eval.png: example images of each class and
     the confusion matrix.
"""
from __future__ import annotations

import glob
import json
import os
import sys

import numpy as np

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, ROOT)

from sim.ai.terrain import MODEL_PATH, TerrainClassifier, features  # noqa: E402
from sim.sensors.camera import CLASSES, synth_patch  # noqa: E402

FIG = os.path.join(ROOT, "docs", "figures", "terrain_eval.png")


def main(per_class: int = 200, seed: int = 2026):
    clf = TerrainClassifier()
    if not clf.load():
        sys.exit(f"no model at {MODEL_PATH}")
    m = clf.model
    print(f"Model: {os.path.relpath(MODEL_PATH, ROOT)}")
    print(f"  Random Forest, {len(m.estimators_)} trees, max depth {m.max_depth}, {m.n_features_in_} features per image")
    print("  trained on 3 500 generated 16x16 images (500 x 7 classes): 2 800 train, 700 held out")
    print(f"  held-out accuracy when trained: {clf.accuracy:.1%}")

    rng = np.random.default_rng(seed)
    cm = np.zeros((len(CLASSES), len(CLASSES)), int)
    for i, c in enumerate(CLASSES):
        for _ in range(per_class):
            img = synth_patch(c, rng, rng.uniform(0.2, 1.0))
            cm[i, int(m.predict(features(img)[None, :])[0])] += 1
    acc = cm.trace() / cm.sum()
    print(f"\nNew test: {cm.sum()} images never seen (seed {seed}): accuracy {acc:.1%}")
    print("  " + " " * 9 + " ".join(f"{c[:6]:>6}" for c in CLASSES) + "   <- predicted")
    for i, c in enumerate(CLASSES):
        print(f"  {c:>9}" + " ".join(f"{v:6d}" for v in cm[i]) + f"   {cm[i, i] / cm[i].sum():.0%}")

    live = []
    for p in sorted(glob.glob(os.path.join(ROOT, "reports", "*", "metrics.json"))):
        try:
            with open(p, encoding="utf-8") as f:
                a = json.load(f).get("terrain_accuracy")
        except (OSError, ValueError):
            continue
        if a is not None:
            live.append((os.path.basename(os.path.dirname(p)), a))
    if live:
        print("\nLive accuracy in real missions (camera frames while driving):")
        for name, a in live:
            print(f"  {a:6.1%}  {name}")

    save_figure(cm, seed)
    print(f"\nFigure: {os.path.relpath(FIG, ROOT)}")


def save_figure(cm, seed):
    import matplotlib
    matplotlib.use("Agg")
    import matplotlib.pyplot as plt

    rng = np.random.default_rng(seed + 1)
    fig = plt.figure(figsize=(13, 5.6))
    gs = fig.add_gridspec(4, 2 * len(CLASSES) + 6, wspace=0.15, hspace=0.25)
    for i, c in enumerate(CLASSES):
        for r in range(4):
            ax = fig.add_subplot(gs[r, i])
            ax.imshow(synth_patch(c, rng, [1.0, 0.8, 0.5, 0.3][r]), cmap="gray", vmin=0, vmax=1)
            ax.set_xticks([]), ax.set_yticks([])
            if r == 0:
                ax.set_title(c, fontsize=9)
            if i == 0:
                ax.set_ylabel(f"light {[1.0, 0.8, 0.5, 0.3][r]}", fontsize=8)
    ax = fig.add_subplot(gs[:, len(CLASSES) + 1:])
    pct = cm / cm.sum(axis=1, keepdims=True)
    ax.imshow(pct, cmap="Greens", vmin=0, vmax=1)
    for i in range(len(CLASSES)):
        for j in range(len(CLASSES)):
            if cm[i, j]:
                ax.text(j, i, f"{pct[i, j]:.0%}" if pct[i, j] >= 0.01 else "<1%", ha="center", va="center", fontsize=8,
                        color="white" if pct[i, j] > 0.6 else "black")
    ax.set_xticks(range(len(CLASSES)), CLASSES, rotation=45, fontsize=8)
    ax.set_yticks(range(len(CLASSES)), CLASSES, fontsize=8)
    ax.set_xlabel("predicted"), ax.set_ylabel("true")
    ax.set_title(f"Confusion matrix on {cm.sum()} new images: {cm.trace() / cm.sum():.1%}", fontsize=10)
    fig.suptitle("Terrain classifier: example camera images per class (left), test result (right)", fontsize=11)
    fig.savefig(FIG, dpi=130, bbox_inches="tight")


if __name__ == "__main__":
    main()
